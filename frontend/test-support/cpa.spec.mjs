import assert from 'node:assert/strict'
import { chromium } from 'playwright'

const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('http://127.0.0.1:5175/test-support/cpa-test.html')
  await page.getByRole('button', { name: 'Explorar actividad' }).click()
  await page.getByRole('button', { name: 'manzana 1' }).click()
  await page.getByRole('button', { name: 'Comprobar y continuar' }).click()
  assert.match(await page.locator('.cpa [role="status"]').innerText(), /Vuelve a leer/)
  await page.getByRole('button', { name: 'manzana 2' }).click()
  await page.getByRole('button', { name: 'Comprobar y continuar' }).click()
  assert.equal(await page.getByText('Colorea un recuadro', { exact: false }).count(), 1)
  await page.getByRole('button', { name: 'Comprobar y continuar' }).click()
  assert.match(await page.locator('.cpa [role="status"]').innerText(), /Cada recuadro/)
  await page.getByRole('button', { name: 'Recuadro 1' }).click()
  await page.getByRole('button', { name: 'Recuadro 2' }).click()
  await page.getByRole('button', { name: 'Comprobar y continuar' }).click()
  await page.getByLabel('Partes elegidas').fill('1')
  await page.getByLabel('Partes en total').fill('0')
  await page.getByRole('button', { name: 'Comprobar fracción' }).click()
  assert.match(await page.locator('.cpa [role="status"]').innerText(), /números enteros/)
  await page.getByLabel('Partes en total').fill('3')
  await page.getByRole('button', { name: 'Comprobar fracción' }).click()
  assert.match(await page.locator('.cpa [role="status"]').innerText(), /Revisa el dibujo/)
  await page.getByLabel('Partes en total').fill('2')
  await page.getByRole('button', { name: 'Comprobar fracción' }).click()
  assert.match(await page.locator('.cpa [role="status"]').innerText(), /¡Lo lograste!/) // 1/2 equivale a 2/4
  await page.locator('summary').first().click()
  assert.equal(await page.getByText(/Conviene seguir practicando fracciones/).count(), 1)
  assert.equal(await page.getByText(/En ecuaciones se observan 4 respuestas correctas de 4/).count(), 1)
  await page.getByRole('button', { name: 'Practicar fracciones' }).click()
  assert.equal(await page.getByLabel('Materia elegida').innerText(), 'fracciones')
  const limitada = page.getByTestId('evidencia-limitada')
  await limitada.locator('summary').click()
  assert.equal(await limitada.getByText(/se necesitan más ejercicios diferentes/).count(), 1)
  assert.equal(await limitada.getByText(/Conviene seguir practicando/).count(), 0)
  await limitada.locator('summary').click()
  await page.screenshot({ path: '/tmp/cpa-escritorio.png', fullPage: true })
  await page.getByRole('button', { name: 'Probar otra situación' }).click()
  assert.equal(await page.getByText('Hay 6 libros. Separa 2 para leer.').count(), 1)
  await page.setViewportSize({ width: 375, height: 812 })
  await page.evaluate(() => document.documentElement.setAttribute('data-myteacher-theme', 'dark'))
  assert.equal(await page.locator('.cpa').evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(30, 41, 59)')
  assert.equal(await page.locator('.familia-resumen').first().evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(41, 54, 76)')
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true)
  await page.screenshot({ path: '/tmp/cpa-movil.png', fullPage: true })
  assert.deepEqual(errors, [])
  console.log('Actividad CPA y resumen familiar: pruebas superadas.')
} finally {
  await browser.close()
}
